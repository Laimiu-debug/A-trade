def infer_symbol(code: str) -> str:
    c = (code or "").strip()
    if len(c) != 6 or not c.isdigit():
        return ""
    if c.startswith(("43", "83", "87", "88", "92")):
        return f"bj{c}"
    if c.startswith(("5", "6", "9", "11")):
        return f"sh{c}"
    return f"sz{c}"


